interface TimetableAutoGenerateDrawerProps {
  open: boolean;
  onClose: () => void;
  /** Which step to land on when the drawer opens (0 = demand, 1 = rules, 2 = generate). */
  initialStep?: number;
  /** Shown in the header so the wizard stays tied to the grid, e.g. "Baby Class · A". */
  scopeLabel?: string;
  focusedGradeId?: string | null;
  onFocusedGradeChange?: (gradeId: string) => void;
  termId: string;
  teachers: Teacher[];
  subjects: Subject[];
  grades: Grade[];
  availableSlotsPerClass: number;
  schoolDays?: number;
  periodNumbers?: number[];
  allocations: TeacherLessonAllocation[];
  rules: TeacherWorkloadRules[];
  loading: boolean;
  onCreateAllocation: (input: {
    termId: string;
    teacherId: string;
    subjectId: string;
    gradeLevelId: string;
    streamId?: string;
    lessonsPerWeek: number;
    preferredDoubleLessons?: number;
  }) => Promise<void>;
  onUpdateAllocation: (input: {
    id: string;
    lessonsPerWeek?: number;
    preferredDoubleLessons?: number;
  }) => Promise<void>;
  onDeleteAllocation: (id: string) => Promise<void>;
  onUpsertRules: (
    input: Partial<TeacherWorkloadRules> & { termId: string; teacherId: string },
  ) => Promise<void>;
  onRunPreflight: () => Promise<TimetablePreflightResult | null>;
  onGenerate: (replaceExisting: boolean) => Promise<{
    createdCount: number;
    unresolvedCount: number;
    warnings: string[];
    entries?: Array<{
      id: string;
      subjectId: string;
      teacherId: string;
      dayTemplatePeriodId: string;
      streamId?: string | null;
      gradeLevelId?: string;
      isDoublePeriod?: boolean;
    }>;
  }>;
  onGenerated: (result?: {
    createdCount: number;
    unresolvedCount: number;
    warnings: string[];
    entries?: Array<{
      id: string;
      subjectId: string;
      teacherId: string;
      dayTemplatePeriodId: string;
      streamId?: string | null;
      gradeLevelId?: string;
      isDoublePeriod?: boolean;
    }>;
  }) => void;
}

